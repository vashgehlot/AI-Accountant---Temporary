"""Build the test books: simulate each client, deliver its paperwork as the client would (dated batches), and write
the answer key for each of its years."""
from __future__ import annotations

import json
import shutil
import sys
from dataclasses import asdict
from datetime import date, timedelta
from pathlib import Path
from typing import Sequence

from testbooks.books.bank import statement_lines
from testbooks.books.chart import write_chart
from testbooks.books.ledger import post
from testbooks.books.year_end import year_end
from testbooks.checks import write_report
from testbooks.dates import add_months, add_working_days, month_end, next_working_day
from testbooks.engine.model import Doc, MoneyAccount
from testbooks.engine.simulate import CLIENTS, World, simulate
from testbooks.key import write_key
from testbooks.render.documents import render_answer, render_doc
from testbooks.render.statements import render_statement
from testbooks.review import write_catalogue, write_review
from testbooks.catalogue import CATEGORIES, load_cases
from testbooks.packs.definitions import SLUGS

# Build step 1 runs the agency's first year and a quarter beyond it (for the bills that arrive after the year end).
DEFAULT_UNTIL = date(2024, 6, 30)
ENGAGEMENT_DAY = date(2023, 4, 12)
LAYOUT_CASES = {"hsbc_csv": "EC-0152"}

README = """TEST BOOKS: SYNTHETIC TEST DATA
================================

Everything in this folder is made up: the clients, people, suppliers, banks and documents. Nothing here is a real
document or a real person's data. It was generated by testbooks (python -m testbooks build) to test bookkeeping
software against an accountant's answer key.

KEY UNREVIEWED: an accountant at the firm has not yet checked the expected treatments in the answer key. Until they
have (see review/), a difference between the key and the software may be the key's fault.

clients/<client>/inbox/<arrival date>/   the paperwork, in the batches the client sends it
clients/<client>/answers/<date>/         the client's replies to the accountant's questions
clients/<client>/key/<period end>/       the answer key for that year (CSV, key.xlsx, accounts.xlsx, checks.txt)

VAT box 5 is signed: negative means a repayment (Making Tax Digital reports it unsigned). The trial balance's
before_answers column is the closing position if the client never answered the accountant's questions.
"""


def _rel(path: Path, folder: Path) -> str:
    return path.relative_to(folder).as_posix()


def _statement_periods(account: MoneyAccount, start: date, until: date) -> list[tuple[date, date]]:
    out = []
    if account.statement_day:
        d = date(start.year, start.month, account.statement_day)
        if d < start:
            d = add_months(d, 1)
        while d <= until:
            out.append((add_months(d, -1) + timedelta(days=1), d))
            d = add_months(d, 1)
    else:
        d = date(start.year, start.month, 1)
        while month_end(d) <= until:
            out.append((d, month_end(d)))
            d = add_months(d, 1)
    return out


def _arrival(on: date, prompt: bool) -> date:
    """When a document reaches the accountant: in the client's monthly batch (the 5th working day after the month
    ends), or, for a pack, the next working day."""
    return next_working_day(on + timedelta(days=1)) if prompt else add_working_days(month_end(on), 5)


def _deliver_statements(world: World, folder: Path, extra_exports, prompt: bool = False) -> tuple[Doc, ...]:
    client, docs = world.client, []
    for acc in client.accounts:
        lines = statement_lines(world, acc.id)
        periods = [(s, e, ()) for s, e in _statement_periods(acc, client.periods[0].start, world.until)]
        periods += [(s, e, tuple(cases)) for a, s, e, cases in extra_exports if a == acc.id]
        for start, end, cases in periods:
            arrival = next_working_day(end + timedelta(days=1)) if prompt else add_working_days(end, 5)
            path = render_statement(acc, lines, start, end, folder / "inbox" / f"{arrival:%Y-%m-%d}")
            shown = [ln for ln in lines if start <= ln.date <= end]
            all_cases = set(cases)
            if acc.layout in LAYOUT_CASES:
                all_cases.add(LAYOUT_CASES[acc.layout])
            if any("E+15" in ln.description for ln in shown):
                all_cases.add("EC-0137")
            docs.append(Doc(f"{acc.id}-statement-{start:%Y%m%d}-{end:%Y%m%d}", "bank_statement", acc.bank,
                            client.name, f"{start:%d %b %Y} to {end:%d %b %Y}", start, treatment="evidence",
                            reason=f"{acc.name} statement export", extra={"cases": tuple(sorted(all_cases)),
                                                                          "file": _rel(path, folder)}))
    return tuple(docs)


def _profile(world: World) -> dict:
    c = world.client
    return {"name": c.name, "kind": c.kind, "address": c.address, "company_number": c.company_number,
            "vat_number": c.vat_number, "vat_quarters_end": list(c.vat_stagger),
            "periods": [{"start": p.start.isoformat(), "end": p.end.isoformat(), "partial": p.partial}
                        for p in c.periods],
            "accounts": [asdict(a) for a in c.accounts],
            "employees": [{"id": e.id, "name": e.name, "director": e.director} for e in c.employees],
            "owners": [{"name": o.name, "share": str(o.share), "loan_account": o.loan_code} for o in c.owners],
            "note": "Synthetic test data, not a real business"}


def build_client(world: World, folder: Path, extra_exports=(), prompt: bool = False) -> Path:
    client = world.client
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    delivered: dict[str, str] = {}
    for deal in world.deals:
        for doc in deal.docs:
            arrival = ENGAGEMENT_DAY if deal.kind == "engagement" else _arrival(doc.date, prompt)
            path = render_doc(doc, deal, client, folder / "inbox" / f"{arrival:%Y-%m-%d}")
            delivered[doc.id] = _rel(path, folder)
        if deal.query is not None:
            files = render_answer(deal.query, deal, client, folder / "answers" / f"{deal.query.answer_date:%Y-%m-%d}")
            delivered[deal.query.id] = _rel(files[0], folder)
            if deal.query.answer_doc is not None:
                delivered[deal.query.answer_doc.id] = _rel(files[1], folder)
    statements = _deliver_statements(world, folder, extra_exports, prompt)
    delivered.update({d.id: d.extra["file"] for d in statements})
    (folder / "profile.json").write_text(json.dumps(_profile(world), indent=2, sort_keys=True) + "\n")
    (folder / "policies.json").write_text(json.dumps(asdict(client.policies), indent=2, sort_keys=True,
                                                     default=str) + "\n")
    write_chart(folder / "chart.csv", client.owners)
    for period in client.periods:
        if period.end > world.until:
            break
        books = post(world, period)
        adjustments = () if period.partial else year_end(world, books, period)
        write_key(world, books, adjustments, period, folder, delivered, statements)
        failed = [r for r in write_report(folder, period.end) if not r.ok]
        if failed:
            raise RuntimeError(f"{client.name} {period.end}: checks failed: "
                               + "; ".join(f"{r.name} ({r.detail})" for r in failed))
        break  # build step 1: the first year only; later steps carry the books forward year by year
    return folder


def build(out: Path, seed: int, clients: Sequence[str], packs: Sequence[str] = (), until: date | None = None) -> list[Path]:
    until = until or DEFAULT_UNTIL
    out.mkdir(parents=True, exist_ok=True)
    registry = CLIENTS()
    folders = []
    for cid in clients:
        define, deals_fn = registry[cid]
        world = simulate(define(), until, seed)
        extra = getattr(sys.modules[deals_fn.__module__], "EXTRA_EXPORTS", ())
        folders.append(build_client(world, out / "clients" / cid, extra))
    cases = {c.id: c for c in load_cases()}
    for case_id in packs:
        define, _ = registry[f"pack:{case_id}"]
        pack = define()
        world = simulate(pack, pack.periods[0].end, seed)
        folder = build_client(world, out / "packs" / f"{case_id}-{SLUGS[case_id]}", prompt=True)
        c = cases[case_id]
        (folder / "case.txt").write_text(
            f"{c.id}: {c.title}\nCategory: {CATEGORIES[c.category]}\nAn accountant expects: {c.expects}\n"
            f"Stakes: {c.stakes}\n", encoding="utf-8")
        folders.append(folder)
    (out / "README.txt").write_text(README, encoding="utf-8")
    write_catalogue(out)
    write_review(out)
    return folders
